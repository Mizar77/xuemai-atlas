const decisionFileAudits: RosterPersonAudit[] = files.flatMap((file) => {
  const unitUrl = unitUrls[file.unitId];
  if (!unitUrl) throw new Error(`Missing roster unit URL for ${file.unitId}`);

  return file.decisions.map((decision) => {
    const rosterName = decision.name ?? decision.rosterName;
    if (!rosterName) throw new Error(`Missing roster name in ${file.unitId}`);
    const mappedDecision = decisionMap[decision.decision];
    if (!mappedDecision) {
      throw new Error(`Unknown roster decision ${decision.decision} in ${file.unitId}`);
    }
    const publishedAtlasId = publishedAtlasIds.get(`${file.unitId}:${rosterName}`)
      ?? publishedByNormalizedName.get(`${file.unitId}:${normalizedRosterPersonName(rosterName)}`);
    return {
      unitUrl,
      rosterName,
      decision: mappedDecision === "candidate_new_pi" && publishedAtlasId ? "included" : mappedDecision,
      atlasPersonId: decision.atlasPersonId ?? publishedAtlasId,
      reason: decision.reason,
      evidenceUrl: decision.profileUrl?.startsWith("http")
        ? decision.profileUrl
        : decision.sourcePageUrl ?? decision.unitUrl ?? unitUrl,
      reviewedAt: file.snapshotAt,
    };
  });
});

