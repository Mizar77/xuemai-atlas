function normalizedRosterPersonName(value: string) {
  const withoutTitle = value
    .replace(/^(prof(?:essor)?|dr)\.?\s+/iu, "")
    .replace(/\s*\([^)]*\)\s*$/u, "")
    .trim();
  const commaParts = withoutTitle.split(",").map((part) => part.trim()).filter(Boolean);
  const reordered = commaParts.length === 2 ? `${commaParts[1]} ${commaParts[0]}` : withoutTitle;
  return reordered.normalize("NFKD").replace(/[^a-z0-9\p{Script=Han}]/giu, "").toLocaleLowerCase();
}

